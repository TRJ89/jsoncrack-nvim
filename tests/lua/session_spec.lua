local assert = require("luassert")
local session_module = require("jsoncrack.session")
local support = require("tests.lua.support")

describe("jsoncrack session lifecycle", function()
    after_each(support.cleanup)

    it("stops the existing session when Toggle is called from another buffer", function()
        local first = support.file_buffer(".json", "{}")
        local second = support.file_buffer(".yaml", "name: value")
        local resolver, child = support.fake_resolver(), support.fake_process()
        local session = support.session_dependencies(session_module, resolver, child)
        session.open(first)
        resolver.succeed(1)
        child.ready(1)
        session.toggle(second)
        assert.are.equal(1, child.stop_count)
        assert.are.equal(1, child.start_count)
        child.exit(1)
    end)

    it("reuses the URL for Open on the same target and rejects a different target", function()
        local first = support.file_buffer(".json", "{}")
        local second = support.file_buffer(".yaml", "name: value")
        local resolver, child = support.fake_resolver(), support.fake_process()
        local session, urls, notices = support.session_dependencies(session_module, resolver, child)
        session.open(first)
        resolver.succeed(1)
        child.ready(1, 43210, string.rep("b", 64))
        session.open(first)
        session.open(second)
        assert.are.equal(1, child.start_count)
        assert.are.same({
            "http://127.0.0.1:43210/#token=" .. string.rep("b", 64),
            "http://127.0.0.1:43210/#token=" .. string.rep("b", 64),
        }, urls)
        assert.are.equal(1, #notices)
        child.exit(1)
    end)

    it("cancels resolution when the real target buffer becomes hidden", function()
        local first = support.file_buffer(".json", "{}")
        local elsewhere = support.buffer(nil)
        support.show(first)
        local resolver, child = support.fake_resolver(), support.fake_process()
        local session = support.session_dependencies(session_module, resolver, child)
        session.open(first)
        support.show(elsewhere)
        resolver.succeed(1)
        assert.are.equal(0, child.start_count)
        assert.are.equal(0, child.stop_count)
    end)

    it("does not restart while stopping and ignores callbacks from an older generation", function()
        local first = support.file_buffer(".json", "{}")
        local second = support.file_buffer(".yaml", "name: value")
        local resolver, child = support.fake_resolver(), support.fake_process()
        local session, urls, notices = support.session_dependencies(session_module, resolver, child)
        session.open(first)
        resolver.succeed(1)
        child.ready(1, 43210, string.rep("c", 64))
        session.stop()
        session.toggle(second)
        assert.are.equal(1, child.start_count)
        assert.are.equal(1, child.stop_count)
        assert.are.equal(1, #notices)
        child.exit(1)
        session.open(second)
        resolver.succeed(2)
        child.ready(2, 43211, string.rep("d", 64))
        child.callbacks[1].on_ready({ port = 9, token = string.rep("e", 64) })
        child.callbacks[1].on_error("old failure")
        child.callbacks[1].on_exit(1)
        session.open(second)
        assert.are.equal(2, child.start_count)
        assert.are.equal(3, #urls)
        assert.is_true(urls[3]:find("43211", 1, true) ~= nil)
        assert.are.equal(1, child.stop_count)
        child.exit(2)
    end)

    it("keeps the session while another split displays the buffer and stops at the last display", function()
        local first = support.file_buffer(".json", "{}")
        local elsewhere = support.buffer(nil)
        support.show(first)
        local resolver, child = support.fake_resolver(), support.fake_process()
        local session = support.session_dependencies(session_module, resolver, child)
        session.open(first)
        resolver.succeed(1)
        child.ready(1)
        local first_window = vim.api.nvim_get_current_win()
        vim.api.nvim_cmd({ cmd = "vsplit" }, {})
        local second_window = vim.api.nvim_get_current_win()
        support.show(elsewhere, second_window)
        assert.are.equal(0, child.stop_count)
        support.show(elsewhere, first_window)
        assert.are.equal(1, child.stop_count)
        child.exit(1)
    end)

    it("cancels Toggle during target resolution and permits a new request", function()
        local first = support.file_buffer(".json", "{}")
        local second = support.file_buffer(".yaml", "name: value")
        local resolver, child = support.fake_resolver(), support.fake_process()
        local session = support.session_dependencies(session_module, resolver, child)
        session.open(first)
        session.toggle(second)
        resolver.succeed(1)
        assert.are.equal(0, child.start_count)
        session.open(second)
        resolver.succeed(2)
        assert.are.equal(1, child.start_count)
        child.exit(1)
    end)

    it("reports Open while starting and warns when unsaved buffer changes are excluded", function()
        local first = support.file_buffer(".json", "{}")
        vim.api.nvim_buf_set_lines(first, 0, -1, false, { "{changed}" })
        local resolver, child = support.fake_resolver(), support.fake_process()
        local session, _, notices = support.session_dependencies(session_module, resolver, child)
        session.open(first)
        session.open(first)
        assert.are.equal(1, #resolver.callbacks)
        resolver.succeed(1)
        assert.are.equal(1, child.start_count)
        assert.is_true(notices[1]:find("starting", 1, true) ~= nil)
        assert.is_true(notices[2]:find("saved file", 1, true) ~= nil)
        child.exit(1)
    end)

    it("stops after browser launch failure and reports a child failure only once", function()
        local first = support.file_buffer(".json", "{}")
        local resolver, child = support.fake_resolver(), support.fake_process()
        local session, _, notices = support.session_dependencies(session_module, resolver, child, {
            open_url = function()
                return nil, "handler failed"
            end,
        })
        session.open(first)
        resolver.succeed(1)
        child.ready(1)
        assert.are.equal(1, child.stop_count)
        assert.are.equal(1, #notices)
        child.error(1, "server failed")
        child.exit(1)
        assert.are.equal(1, #notices)
    end)

    it("notifies once when the server exits unexpectedly", function()
        local first = support.file_buffer(".json", "{}")
        local resolver, child = support.fake_resolver(), support.fake_process()
        local session, _, notices = support.session_dependencies(session_module, resolver, child)
        session.open(first)
        resolver.succeed(1)
        child.ready(1)
        child.exit(1)
        child.error(1, "late error")
        child.exit(1, 1)
        assert.are.equal(1, #notices)
    end)

    it("uses the real server for a special-character path and observes Open and Stop", function()
        local target_module = require("jsoncrack.target")
        local process_module = require("jsoncrack.process")
        local contents = '{"name":"日本語"}\n'
        local bufnr = support.file_buffer(".json", contents, "日本語 ' $().json")
        support.show(bufnr)
        local urls, notices = {}, {}
        local exited, exit_code = false, nil
        local session = session_module.new({
            resolve = target_module.resolve,
            start_process = function(target, callbacks)
                return process_module.start(target, {
                    on_ready = callbacks.on_ready,
                    on_error = callbacks.on_error,
                    on_exit = function(code)
                        exited = true
                        exit_code = code
                        callbacks.on_exit(code)
                    end,
                })
            end,
            open_url = function(url)
                urls[#urls + 1] = url
                return true
            end,
            notify = function(message)
                notices[#notices + 1] = message
            end,
        })
        session.open(bufnr)
        assert.is_true(support.await(function()
            return #urls == 1 or #notices > 0
        end, 5000))
        assert.are.equal(0, #notices, notices[1])
        local port, token = urls[1]:match("^http://127%.0%.0%.1:(%d+)/#token=([0-9a-f]+)$")
        assert.is_truthy(port)
        local response = support.http_request(tonumber(port), token)
        assert.is_true(response:match("^HTTP/1%.1 200") ~= nil)
        local body = response:match("\r\n\r\n(.*)$")
        local snapshot = vim.json.decode(body)
        assert.are.equal("日本語 ' $().json", snapshot.display_name)
        assert.are.equal(contents, snapshot.text)
        session.open(bufnr)
        assert.are.equal(urls[1], urls[2])
        session.stop()
        assert.is_true(support.await(function()
            return exited
        end, 3000))
        assert.are.equal(0, exit_code)
        assert.is_true(support.await_port_closed(tonumber(port), 3000))
    end)

    it("stops on buffer rename, unload, wipeout, and VimLeavePre", function()
        local events = { "BufFilePost", "BufUnload", "BufWipeout", "VimLeavePre" }
        for _, event in ipairs(events) do
            local path = support.make_file(".json", "{}")
            local bufnr = support.buffer(path)
            support.show(bufnr)
            local resolver, child = support.fake_resolver(), support.fake_process()
            local session = support.session_dependencies(session_module, resolver, child)
            session.open(bufnr)
            resolver.succeed(1)
            child.ready(1)
            if event == "BufFilePost" then
                vim.api.nvim_buf_set_name(bufnr, path .. ".renamed")
            elseif event == "BufUnload" then
                support.show(support.buffer(nil))
                vim.api.nvim_cmd({ cmd = "bunload", args = { tostring(bufnr) } }, {})
            elseif event == "BufWipeout" then
                vim.api.nvim_buf_delete(bufnr, { force = true })
            else
                vim.api.nvim_exec_autocmds("VimLeavePre", { modeline = false })
            end
            assert.are.equal(1, child.stop_count, event .. " should stop the process")
            child.exit(1)
        end
    end)
end)
